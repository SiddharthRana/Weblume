import { describe, expect, it } from 'vitest';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';
import { REPORT_LIMITATIONS } from '@weblume/shared';
import { renderReportPdf } from '../../src/reports/report-pdf';
import { own, sampleReport } from './fixtures';

async function pdfText(buf: Buffer): Promise<{ pages: number; text: string }> {
  const pdf = await getDocument({ data: new Uint8Array(buf), useSystemFonts: false }).promise;
  let text = '';
  for (let i = 1; i <= pdf.numPages; i++) {
    const page = await pdf.getPage(i);
    const content = await page.getTextContent();
    text += content.items.map((it) => ('str' in it ? it.str : '')).join(' ') + '\n';
  }
  return { pages: pdf.numPages, text: text.replace(/\s+/g, ' ') };
}

const opts = { siteUrl: 'https://weblume.test', generatedAt: new Date('2026-10-30T08:00:00Z') };

describe('renderReportPdf', () => {
  it('renders a valid PDF with the report content and limitations notice', async () => {
    const buf = await renderReportPdf(sampleReport(), opts);
    expect(buf.subarray(0, 5).toString()).toBe('%PDF-');
    const { text, pages } = await pdfText(buf);
    expect(pages).toBeGreaterThanOrEqual(2);
    expect(text).toContain('https://bakery.example/');
    expect(text).toContain('Lighthouse scores');
    expect(text).toContain('54');
    expect(text).toContain('Not measured');
    expect(text).toContain('Some links on this page are broken');
    expect(text).toContain('https://www.bakery.example/old-menu → HTTP 404');
    expect(text).toContain('Didn’t finish in time');
    expect(text).toContain('Pâtisserie');
    expect(text).toContain('Москва');
    expect(text).toContain(REPORT_LIMITATIONS.slice(0, 60));
    expect(text).toContain(`Page 1 of ${pages}`);
    expect(text).toContain('Generated by Weblume (weblume.test)');
  });

  it('says honestly when there are no Lighthouse scores and no findings', async () => {
    const buf = await renderReportPdf(
      sampleReport({ lighthouse: null, findings: [], status: 'partial' }),
      opts,
    );
    const { text } = await pdfText(buf);
    expect(text).toContain('Lighthouse scores aren’t available for this scan');
    expect(text).toContain('No issues were found by the checks that ran.');
    expect(text).toContain('Some checks couldn’t be completed');
  });

  it('handles long reports and hostile text without failing', async () => {
    const many = Array.from({ length: 60 }, (_, i) =>
      own(
        'seo.title.length',
        { title: `T${i}\u0000\u0007 ${'x'.repeat(300)}`, length: 300 },
        {
          id: `f${i}`,
        },
      ),
    );
    const buf = await renderReportPdf(sampleReport({ findings: many }), opts);
    const { pages } = await pdfText(buf);
    expect(pages).toBeGreaterThan(5);
  });
});
