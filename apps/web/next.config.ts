import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import createMDX from '@next/mdx';
import type { NextConfig } from 'next';
import { PHASE_PRODUCTION_BUILD } from 'next/constants';
import { buildCsp } from './csp';

const securityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
  { key: 'Content-Security-Policy', value: buildCsp() },
  // Non-production builds (e.g. dev.weblu.me) stay out of search results.
  ...(process.env.NEXT_PUBLIC_NOINDEX === 'true'
    ? [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }]
    : []),
];

// Shared reports: the token is in the path, so never send it to other sites.
const sharedReportHeaders = [
  { key: 'Referrer-Policy', value: 'no-referrer' },
  { key: 'X-Robots-Tag', value: 'noindex, nofollow' },
];

/**
 * Cloudflare Pages response headers (https://developers.cloudflare.com/pages/configuration/headers/).
 * Generated rather than committed because the CSP lists the API and Supabase origins from the build's
 * env. `! Referrer-Policy` drops the site-wide value so shared reports send only `no-referrer`.
 */
function cloudflareHeaders(): string {
  const lines = (hs: { key: string; value: string }[]) => hs.map((h) => `  ${h.key}: ${h.value}`);
  return [
    '# Generated by next.config.ts at build time. Do not edit.',
    '/*',
    ...lines(securityHeaders),
    '',
    '/r/*',
    '  ! Referrer-Policy',
    ...lines(sharedReportHeaders),
    '',
  ].join('\n');
}

const baseConfig: NextConfig = {
  pageExtensions: ['ts', 'tsx', 'md', 'mdx'],
  reactCompiler: true,
  typedRoutes: true,
  poweredByHeader: false,
  transpilePackages: ['@weblume/shared', '@weblume/design-tokens'],
};

// Plugins are given by name so the config stays serializable for Turbopack.
const withMDX = createMDX({ options: { remarkPlugins: [['remark-gfm', {}]] } });

/**
 * Production builds are a static export (`out/`) served by Cloudflare Pages: every page renders in the
 * browser and talks to the API directly. Reports (`/scan/<id>`, `/r/<token>`) are exported once as a
 * placeholder and public/_redirects rewrites every id to it. `next dev` stays a normal server so those
 * routes work with real ids locally, and keeps sending the same headers via `headers()`, which a static
 * export ignores.
 */
export default function config(phase: string): NextConfig {
  if (phase === PHASE_PRODUCTION_BUILD) {
    mkdirSync(join(process.cwd(), 'public'), { recursive: true });
    writeFileSync(join(process.cwd(), 'public', '_headers'), cloudflareHeaders());
    return withMDX({ ...baseConfig, output: 'export' });
  }
  return withMDX({
    ...baseConfig,
    async headers() {
      return [
        { source: '/:path*', headers: securityHeaders },
        { source: '/r/:path*', headers: sharedReportHeaders },
      ];
    },
  });
}
